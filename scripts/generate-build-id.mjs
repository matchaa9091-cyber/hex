import fs from "node:fs";

// A fresh ID on every build lets the Worker reject edge/R2 HTML cached by an
// older deploy, including pages with no X-Hex-Build/customMetadata yet.
const BUILD_ID = `${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 8)}`;
const file = "scripts/build-id.generated.mjs";

fs.writeFileSync(
  file,
  `// Generated by scripts/generate-build-id.mjs. Do not edit.\nexport const BUILD_ID = ${JSON.stringify(BUILD_ID)};\n`,
  "utf8"
);

console.log(`BUILD_ID=${BUILD_ID}`);
